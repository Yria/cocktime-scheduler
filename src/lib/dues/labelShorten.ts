/**
 * 묶음 라벨의 **표시용** 축약. 서버 라벨은 '2026-09-06 · 에이트민턴 · 19:00–22:00'
 * 이나 '09/06 19:00 체육관 #12' 처럼 길어서 고정 폭 레일 옆 본문 열(390px에서 약
 * 220px)에 들어가지 않는다.
 *
 * 원문 라벨은 접근명·검색·select 옵션의 계약이므로 **절대 바꾸지 않는다**.
 * 이 함수는 필터 칩·처리내역 줄처럼 시각 표시 전용 자리에서만 쓴다.
 */
export function shortGroupLabel(label: string): string {
	let out = label.trim();
	// 내부 식별자(#12)는 총무 어휘가 아니다 — 표시에서 뺀다.
	out = out.replace(/\s*#\d+\s*$/, "");
	// 2026-09-06 / 2026.09.06 / 09/06 → 9/6
	out = out.replace(
		/^(\d{4})[-.](\d{2})[-.](\d{2})/,
		(_, _y, m, d) => `${Number(m)}/${Number(d)}`,
	);
	out = out.replace(
		/^(\d{2})\/(\d{2})/,
		(_, m, d) => `${Number(m)}/${Number(d)}`,
	);
	// 19:00–22:00 → 19:00 (종료 시각은 상세에서 본다)
	out = out.replace(/(\d{1,2}:\d{2})\s*[–~-]\s*\d{1,2}:\d{2}/, "$1");
	return out.replace(/\s*·\s*$/, "");
}
